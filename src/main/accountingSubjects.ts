export function loadStandardSubjects(standardCode: string): VoucherSubjectSeed[] {
  const key = standardCode === "SBE_2011" ? "SBE_2011" : "ASBE_2006";
  return STANDARD_SUBJECTS[key].trim().split(/\r?\n/).map((row) => {
    const separator = row.indexOf("|");
    const code = row.slice(0, separator);
    const nameParts = row.slice(separator + 1).split("/").map((name) => name.trim());
    return {
      code,
      name: nameParts[0] ?? "",
      manual: true,
      requiresAttachment: ATTACHMENT_REQUIRED_CODES.has(code),
      fixedDetails: nameParts.slice(1)
    };
  });
}
